from PIL import Image, ImageDraw, ImageFont
import numpy as np
import os
import sys

def create_test_image():
    """创建测试图像"""
    print("🎨 创建Pixly验证测试图像...")
    
    # 创建基础图像 (1920x1080, RGB)
    width, height = 1920, 1080
    image = Image.new('RGB', (width, height), color=(30, 30, 30))
    draw = ImageDraw.Draw(image)
    
    # 绘制渐变背景
    for y in range(height):
        gradient_color = int(30 + (y / height) * 200)
        for x in range(width):
            hue_shift = int((x / width) * 50)
            color = (
                min(255, gradient_color + hue_shift),
                min(255, gradient_color + hue_shift // 2),
                min(255, gradient_color + hue_shift // 3)
            )
            image.putpixel((x, y), color)
    
    # 添加测试图案
    draw.rectangle([100, 100, 500, 300], fill=(255, 100, 100))
    draw.rectangle([600, 200, 900, 400], fill=(100, 255, 100))
    draw.rectangle([1000, 300, 1300, 500], fill=(100, 100, 255))
    
    # 添加圆形
    draw.ellipse([200, 600, 400, 800], fill=(255, 255, 100))
    draw.ellipse([600, 700, 800, 900], fill=(255, 100, 255))
    draw.ellipse([1000, 650, 1200, 850], fill=(100, 255, 255))
    
    # 添加文字 (使用默认字体)
    try:
        # 尝试使用系统字体
        font_size = 48
        draw.text((50, 50), "🚀 PIXLY RUST内核验证测试", fill=(255, 255, 255))
        draw.text((50, 120), "Rust Kernel Functional Test", fill=(200, 200, 200))
        draw.text((50, 200), f"图像尺寸: {width}x{height}", fill=(255, 200, 100))
        draw.text((50, 280), "🎯 测试状态: 系统运行正常", fill=(100, 255, 100))
        
        # 添加技术信息
        draw.text((50, 950), "Generated by: Pixly Performance Core", fill=(150, 150, 150))
        draw.text((50, 1000), "Rust + Python Bridge Integration Test", fill=(150, 150, 150))
        
    except Exception as e:
        print(f"字体加载警告: {e}, 使用默认渲染")
        draw.text((50, 50), "PIXLY RUST KERNEL TEST", fill=(255, 255, 255))
    
    # 保存测试图像
    test_dir = "/tmp/pixly_test"
    os.makedirs(test_dir, exist_ok=True)
    
    # 保存为多种格式进行测试
    formats = {
        'png': f"{test_dir}/pixly_test_input.png",
        'jpeg': f"{test_dir}/pixly_test_input.jpg", 
        'bmp': f"{test_dir}/pixly_test_input.bmp"
    }
    
    for fmt, path in formats.items():
        try:
            if fmt == 'jpeg':
                # JPEG不支持透明度
                rgb_image = image.convert('RGB')
                rgb_image.save(path, 'JPEG', quality=95)
            else:
                image.save(path, fmt.upper())
            print(f"  ✅ 创建 {fmt.upper()} 格式: {path}")
        except Exception as e:
            print(f"  ❌ {fmt.upper()} 格式创建失败: {e}")
    
    return formats['png']  # 返回PNG路径作为主要测试文件

def create_complex_test_image():
    """创建复杂测试图像用于性能测试"""
    print("🔬 创建复杂性能测试图像...")
    
    # 创建复杂图像
    width, height = 2560, 1440
    
    # 生成随机噪声背景
    noise = np.random.randint(0, 256, (height, width, 3), dtype=np.uint8)
    noise_image = Image.fromarray(noise, 'RGB')
    
    # 创建渐变层
    gradient = Image.new('RGB', (width, height), color=(0, 0, 0))
    draw = ImageDraw.Draw(gradient)
    
    # 复杂图案
    for i in range(50):
        x = np.random.randint(0, width-200)
        y = np.random.randint(0, height-200)
        w = np.random.randint(50, 200)
        h = np.random.randint(50, 200)
        color = tuple(np.random.randint(0, 256, 3))
        draw.rectangle([x, y, x+w, y+h], fill=color)
    
    # 合成图像
    blended = Image.blend(noise_image, gradient, 0.3)
    
    # 保存复杂测试图像
    complex_path = "/tmp/pixly_test/pixly_complex_test.png"
    blended.save(complex_path, "PNG")
    print(f"  ✅ 复杂测试图像: {complex_path}")
    
    return complex_path

def verify_image_creation():
    """验证图像创建结果"""
    print("🔍 验证图像创建结果...")
    
    test_dir = "/tmp/pixly_test"
    
    for filename in os.listdir(test_dir):
        if filename.endswith(('.png', '.jpg', '.bmp')):
            filepath = os.path.join(test_dir, filename)
            try:
                with Image.open(filepath) as img:
                    size = img.size
                    mode = img.mode
                    print(f"  ✅ {filename}: {size[0]}x{size[1]} ({mode})")
            except Exception as e:
                print(f"  ❌ {filename}: 验证失败 - {e}")

