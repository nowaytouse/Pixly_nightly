package main

import (
	"os"
	"strings"
)

// Language 语言类型
type Language string

const (
	LangEN   Language = "en"
	LangZhCN Language = "zh_CN"
	LangZhTW Language = "zh_TW"
	LangJaJP Language = "ja_JP"
)

// 当前语言（全局变量）
var currentLang Language

// GetLanguage 获取系统语言
func GetLanguage() Language {
	// 1. 检查环境变量 PIXLY_LANG（优先级最高）
	env := os.Getenv("PIXLY_LANG")
	if env != "" {
		return parseLang(env)
	}

	// 2. 检测系统 LANG 环境变量
	lang := os.Getenv("LANG")
	if strings.Contains(lang, "zh_CN") || strings.Contains(lang, "zh-CN") {
		return LangZhCN
	} else if strings.Contains(lang, "zh_TW") || strings.Contains(lang, "zh-TW") || strings.Contains(lang, "zh_HK") {
		return LangZhTW
	} else if strings.Contains(lang, "ja") {
		return LangJaJP
	}

	// 3. 默认英语（通用语言）
	return LangEN
}

// parseLang 解析语言字符串
func parseLang(s string) Language {
	s = strings.ToLower(strings.TrimSpace(s))
	switch s {
	case "zh_cn", "zh-cn", "cn", "chinese", "简体中文":
		return LangZhCN
	case "zh_tw", "zh-tw", "tw", "zh_hk", "zh-hk", "繁體中文", "繁体中文":
		return LangZhTW
	case "ja", "ja_jp", "ja-jp", "japanese", "日本語":
		return LangJaJP
	case "en", "en_us", "en-us", "english":
		return LangEN
	default:
		return LangEN // 默认英语
	}
}

// T 获取翻译文本
func T(key string) string {
	translations, ok := i18nDict[currentLang]
	if !ok {
		translations = i18nDict[LangEN] // Fallback
	}

	text, ok := translations[key]
	if !ok {
		return key // 如果找不到翻译，返回key本身
	}
	return text
}

